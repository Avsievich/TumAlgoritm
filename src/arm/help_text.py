"""Тексты справки рабочего места.

Здесь только пояснения для человека. Формулы расчёта в этот модуль
не переносятся: окно показывает готовый текст рядом с числом.
Имена карточек не должны совпадать с разделами инструкции:
список на экране «Справка» общий, и тест это проверяет.
"""

from dataclasses import dataclass

from arm.help_guide import full_guide


@dataclass(frozen=True)
class IndicatorHelp:
    """Пояснение одного показателя для экрана «Справка».

    Attributes:
        name: имя, как оно написано в отчёте или на экране.
        short: одна строка под карточкой на экране результатов.
        meaning: что это за величина или параметр.
        how: как программа это считает или откуда берёт.
        why: зачем поле нужно при чтении результата.
        span: диапазон или значение по умолчанию.
        reading: как читать число на экране и в книге.
        mistake: типичная ошибка чтения.
    """

    name: str
    short: str
    meaning: str
    how: str
    why: str
    span: str
    reading: str
    mistake: str


# Полный текст инструкции. Экран «Справка» показывает его целиком
# и по разделам. Короткий порядок лежит внутри этого текста.
HOW_TO = full_guide()


def _item(
    name: str,
    short: str,
    meaning: str,
    how: str,
    why: str,
    span: str,
    reading: str,
    mistake: str,
) -> IndicatorHelp:
    """Собирает карточку справки без длинной записи на месте вызова."""
    return IndicatorHelp(
        name,
        short,
        meaning,
        how,
        why,
        span,
        reading,
        mistake,
    )


