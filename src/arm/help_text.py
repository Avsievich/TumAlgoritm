BY_NAME = {item.name: item for item in INDICATORS}


def help_for(name: str) -> IndicatorHelp:
    """Возвращает пояснение показателя по имени в отчёте.

    Args:
        name: ключ из INDICATORS, например «MDO».

    Returns:
        Карточка справки.

    Raises:
        KeyError: такого показателя в справке нет.
    """
    return BY_NAME[name]


def format_help(item: IndicatorHelp) -> str:
    """Собирает подробный текст карточки для экрана справки.

    На экране видны смысл, расчёт, назначение, диапазон,
    способ чтения и типичная ошибка. Короткая строка short
    остаётся под карточкой результатов и сюда не копируется.

    Args:
        item: карточка из INDICATORS.

    Returns:
        Готовый текст для виджета справки.
    """
    return (
        f"{item.name}\n\n"
        f"Что это. {item.meaning}\n\n"
        f"Как считается. {item.how}\n\n"
        f"Зачем. {item.why}\n\n"
        f"Диапазон: {item.span}\n\n"
        f"Как читать. {item.reading}\n\n"
        f"Частая ошибка: {item.mistake}\n"
    )
