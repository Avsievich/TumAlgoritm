_BY_TITLE = {title: text for title, text in CHAPTERS}


def guide_names() -> list[str]:
    """Имена пунктов инструкции для списка на экране «Справка».

    Returns:
        Сначала текст целиком, затем названия разделов.
    """
    titles = [title for title, _text in CHAPTERS]
    return [GUIDE_TITLE, *titles]


def guide_for(name: str) -> str:
    """Возвращает текст инструкции по имени пункта.

    Args:
        name: «Как работать» либо название раздела.

    Returns:
        Готовый текст для поля справки.

    Raises:
        KeyError: такого раздела в инструкции нет.
    """
    if name == GUIDE_TITLE:
        return full_guide()
    try:
        body = _BY_TITLE[name]
    except KeyError as exc:
        raise KeyError(f"В инструкции нет раздела «{name}»") from exc
    return f"{name}\n\n{body.strip()}\n"


def full_guide() -> str:
    """Собирает инструкцию целиком, раздел за разделом."""
    parts = ["Как работать с программой", "", _INTRO.strip(), ""]
    for title, body in CHAPTERS:
        parts.append(title)
        parts.append("")
        parts.append(body.strip())
        parts.append("")
    return "\n".join(parts).rstrip() + "\n"
